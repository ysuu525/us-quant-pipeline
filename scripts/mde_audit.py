"""本项目各类比较的实际最小可检出效应（MDE）—— 用实测标准误，不用假设。

问题：预注册的粗筛判据要求「99% 块自助 CI 全体 > 0」。一整天下来没有任何
臂间比较达到过这个标准。本脚本查：这条规则**能不能**触发。
"""
import numpy as np

# 全部来自本项目实测（逐日配对、NW 稳健标准误）
CASES = [
    # (名称, 配对 NW SE, 天数, 参照量, 参照量名称, 来源)
    ("臂间 全池 RankIC 差", 0.0088, 881, 0.0207, "信号本身 IC",
     "K11 FT-ZS 配对"),
    ("臂间 top500 RankIC 差", 0.0112, 881, 0.0258, "top500 IC",
     "K11 FT-ZS 配对"),
    ("臂间 RankIC 差(4折)", 0.01214, 504, 0.0207, "信号本身 IC",
     "K7a ZS-FT 配对"),
    ("臂间 毛日收益差(bp)", 3.2408, 881, 4.1587, "毛日收益(bp)",
     "K11 FT-ZS 配对"),
    ("lb200-lb90 RankIC 差", 0.0053, 881, 0.0207, "信号本身 IC",
     "compare_arms 99%CI 半宽/2.576 反推"),
]

print(f"{'比较类型':<26}{'实测SE':>10}{'天数':>7}{'99%门槛':>11}{'MDE80':>10}"
      f"{'参照量':>11}{'门槛/参照':>11}")
print("-" * 90)
for name, se, n, ref, refname, src in CASES:
    thr99 = 2.576 * se      # 99% CI 全体 > 0 所需的点估计
    mde80 = 2.80 * se       # 80% 功效 + 5% 双侧 的最小可检出效应
    print(f"{name:<26}{se:>10.5f}{n:>7}{thr99:>11.5f}{mde80:>10.5f}"
          f"{ref:>11.4f}{thr99/ref:>10.2f}×")

print("\n" + "=" * 90)
print("要把「臂间差异 20%」做成确认性检验，需要多少数据？")
print("=" * 90)
se0, n0 = 0.0088, 881
for rel in (0.50, 0.30, 0.20, 0.10):
    eff = 0.0207 * rel
    se_need = eff / 2.80                    # 80% 功效
    n_need = n0 * (se0 / se_need) ** 2
    print(f"  分辨 {rel:.0%} 的相对差（绝对 {eff:.5f}）：需 SE={se_need:.5f}"
          f" -> **{n_need:,.0f} 个交易日 = {n_need/252:,.0f} 年**")

print("\n" + "=" * 90)
print("对照：什么比较是**有**功效的（本项目实测）")
print("=" * 90)
for nm, val, t, note in (
        ("信号 vs 零（全池 RankIC）", 0.02067, 3.63, "881 天"),
        ("信号 vs 树基线", 0.0207, None, "差一个量级，不需检验"),
        ("ΔADV 的跨年代 DiD", 0.01138, None, "95%CI [+0.0034,+0.0191], P=0.998"),
        ("η（IC->价差乘子）", 0.902, None, "95%CI [0.813,0.960]"),
        ("σ_cs 年趋势", -0.396, -2.99, "95%CI [-0.630,-0.198]"),
        ("K7b 早期 Δ（top500-全池）", -0.00620, -2.23, "504 天"),
):
    tt = f"t={t:+.2f}" if t else ""
    print(f"  {nm:<28}{val:>+10.5f}  {tt:<10}{note}")
print("\n  规律：**「信号 vs 零」与「年代 vs 年代」有功效；「变体 A vs 变体 B」没有。**")
